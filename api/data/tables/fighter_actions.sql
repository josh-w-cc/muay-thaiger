CREATE TABLE IF NOT EXISTS fighter_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action BIGINT NOT NULL REFERENCES actions(id) ON DELETE CASCADE,
  fighter BIGINT NOT NULL REFERENCES fighters(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  touched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(fighter, action)
);
