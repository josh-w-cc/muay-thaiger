CREATE TABLE IF NOT EXISTS entity_components (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
  component BIGINT NOT NULL REFERENCES components(id) ON DELETE CASCADE,
  data JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(entity, component)
);

CREATE OR REPLACE TRIGGER entity_components_updated_at
  BEFORE UPDATE ON entity_components
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
