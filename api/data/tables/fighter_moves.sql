CREATE TABLE IF NOT EXISTS fighter_moves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fighter BIGINT NOT NULL REFERENCES fighters(id) ON DELETE CASCADE,
  move BIGINT NOT NULL REFERENCES moves(id) ON DELETE CASCADE,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  touched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(fighter, move)
);
