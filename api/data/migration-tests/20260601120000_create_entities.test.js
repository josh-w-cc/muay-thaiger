import assert from 'node:assert/strict';
import {describe, it} from 'node:test';

import {down, up} from '../migrations/20260601120000_create_entities.js';


describe('20260601120000_create_entities migration', () => {
  it('creates entities table with timestamps and updated_at trigger', async () => {
    const calls = [];
    const knex = {
      raw: async (sql) => {
        calls.push(sql);
        return [];
      },
    };

    await up(knex);

    assert.equal(calls.length, 1);
    assert.match(calls[0], /CREATE TABLE IF NOT EXISTS entities/);
    assert.match(calls[0], /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    assert.match(calls[0], /created_at TIMESTAMPTZ NOT NULL DEFAULT NOW\(\)/);
    assert.match(calls[0], /updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW\(\)/);
    assert.match(calls[0], /CREATE OR REPLACE TRIGGER entities_updated_at/);
    assert.match(calls[0], /BEFORE UPDATE ON entities/);
    assert.match(calls[0], /EXECUTE FUNCTION update_updated_at_column\(\)/);
  });

  it('drops entities on rollback', async () => {
    const calls = [];
    const knex = {
      raw: async (sql) => {
        calls.push(sql);
        return [];
      },
    };

    await down(knex);

    assert.deepEqual(calls, ['DROP TABLE IF EXISTS entities CASCADE']);
  });
});
